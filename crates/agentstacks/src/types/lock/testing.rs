//! Shared text for the tests of the lock group.
//!
//! # Responsibilities
//!
//! - [`example_lock`] is the documented `agentstacks.lock` example with each hex placeholder
//!   replaced by fixed lowercase hex of the right length, so one text is parsed, written back and
//!   compared by several tests.
//!
//! # Non-responsibilities
//!
//! It is compiled for tests only and holds no rule.

/// A 40-character commit id.
pub(super) const HEX40: &str = "0123456789abcdef0123456789abcdef01234567";

/// A 64-character digest.
pub(super) const HEX64: &str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

/// The documented lock, hex filled, ending with one newline.
pub(super) fn example_lock() -> String {
    format!(
        "api = 1\n\
         # Generated by agentstacks. Do not edit.\n\
         \n\
         [airsl]\n\
         version = \"0.1.4\"\n\
         \n\
         [[tool]]\n\
         name    = \"claude\"\n\
         version = \"0.1.0\"\n\
         git     = \"https://github.com/airsstack/agentstacks\"\n\
         tag     = \"packs-v0.1.0\"\n\
         subdir  = \"extensions/claude\"\n\
         rev     = \"{HEX40}\"\n\
         tree    = \"sha256:{HEX64}\"\n\
         \n\
         [[pack]]\n\
         name    = \"core\"\n\
         version = \"0.3.0\"\n\
         git     = \"https://github.com/airsstack/agentstacks\"\n\
         tag     = \"packs-v0.1.0\"\n\
         subdir  = \"packs/core\"\n\
         rev     = \"{HEX40}\"\n\
         tree    = \"sha256:{HEX64}\"\n\
         \n\
         [[pack]]\n\
         name    = \"team-lint\"\n\
         version = \"0.1.0\"\n\
         path    = \"packs/team-lint\"\n\
         tree    = \"sha256:{HEX64}\"\n\
         \n\
         [[file]]\n\
         path = \".claude/skills/discuss/SKILL.md\"\n\
         hash = \"sha256:{HEX64}\"\n\
         by   = \"core\"\n"
    )
}
