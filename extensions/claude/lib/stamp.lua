-- The generated-file stamp for files this extension owns.
--
-- Pure: decides from the target path's suffix only. Shared files are the
-- extension's `reads` targets, both JSON, and JSON cannot carry a comment, so
-- the suffix rule already excludes them; copied files never pass through here.

local M = {}

local STAMPS = {
  [".md"] = "<!-- generated by agentstacks — change agentstacks.toml and re-run apply, do not edit -->",
  [".lua"] = "-- generated by agentstacks — change agentstacks.toml and re-run apply, do not edit",
}

-- The stamp line for `path`, or nil when its suffix is not stamped.
local function stamp_for(path)
  if path:sub(-3) == ".md" then
    return STAMPS[".md"]
  end
  if path:sub(-4) == ".lua" then
    return STAMPS[".lua"]
  end
  return nil
end

-- The byte index just after the frontmatter closing line, or 0 when the
-- content does not start with a frontmatter block.
local function after_frontmatter(content)
  if content:sub(1, 4) ~= "---\n" then
    return 0
  end
  local close = content:find("\n---\n", 4, true)
  if close == nil then
    return 0
  end
  return close + 4
end

-- `content` with the stamp for `path` inserted: after the frontmatter block
-- for Markdown that has one, otherwise as the first line. Content already
-- stamped at the insertion point (CRLF included) is returned unchanged.
function M.stamp(path, content)
  local stamp = stamp_for(path)
  if stamp == nil then
    return content
  end
  if content == "" then
    return stamp .. "\n"
  end
  local at = 0
  if path:sub(-3) == ".md" then
    at = after_frontmatter(content)
  end
  local line = content:sub(at + 1):match("^([^\n]*)")
  if line ~= nil and (line:gsub("\r$", "")) == stamp then
    return content
  end
  return content:sub(1, at) .. stamp .. "\n" .. content:sub(at + 1)
end

return M
