local stamp = require("stamp")

local MD = "<!-- generated by agentstacks — change agentstacks.toml and re-run apply, do not edit -->"
local LUA = "-- generated by agentstacks — change agentstacks.toml and re-run apply, do not edit"

return {
  stamps_markdown_after_frontmatter = function()
    local out = stamp.stamp("x/SKILL.md", "---\nname: a\n---\nbody\n")
    assert(out == "---\nname: a\n---\n" .. MD .. "\nbody\n", out)
  end,

  stamps_markdown_without_frontmatter_first_line = function()
    assert(stamp.stamp("x/a.md", "body\n") == MD .. "\nbody\n")
  end,

  stamps_lua_first_line_and_skips_json = function()
    assert(stamp.stamp("x/a.lua", "return {}\n") == LUA .. "\nreturn {}\n")
    assert(stamp.stamp("x/a.json", "{}\n") == "{}\n")
    assert(stamp.stamp("x/a.MD", "body\n") == "body\n")
    assert(stamp.stamp("x/a.txt", "body\n") == "body\n")
  end,

  stamps_empty_content = function()
    assert(stamp.stamp("x/a.md", "") == MD .. "\n")
  end,

  does_not_double_stamp = function()
    local once = stamp.stamp("x/SKILL.md", "---\nname: a\n---\nbody\n")
    assert(stamp.stamp("x/SKILL.md", once) == once)
    local crlf = "---\r\nname: a\r\n---\r\n" .. MD .. "\r\nbody\r\n"
    -- CRLF frontmatter is not the LF form, so the stamp goes first; the line
    -- after it is not the stamp and no second copy is added on re-stamp of LF.
    local out = stamp.stamp("x/a.lua", LUA .. "\r\nreturn {}\r\n")
    assert(out == LUA .. "\r\nreturn {}\r\n", out)
    assert(crlf:find(MD, 1, true) ~= nil)
  end,
}
